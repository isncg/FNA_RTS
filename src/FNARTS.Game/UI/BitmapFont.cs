    /// <summary>
    /// Minimal procedurally-generated monospace bitmap font.
    /// Covers ASCII 32-126 (printable) at 8×12 glyphs in a 16×6 grid.
    /// No external spritefont file needed.
    /// </summary>
    public class BitmapFont : IDisposable
    {
        public const int GLYPH_W = 8;
        public const int GLYPH_H = 12;
        private const int COLS = 16;
        private const int ROWS = 6;

        public Texture2D Texture { get; }

        private readonly Rectangle[] _glyphRects = new Rectangle[128];

        public BitmapFont(GraphicsDevice device)
        {
            int texW = COLS * GLYPH_W;  // 128
            int texH = ROWS * GLYPH_H;  // 72
            var data = new Color[texW * texH];
            Array.Fill(data, Color.Transparent);

            for (int ch = 32; ch < 127; ch++)
            {
                int idx = ch - 32;
                int col = idx % COLS;
                int row = idx / COLS;
                int ox = col * GLYPH_W;
                int oy = row * GLYPH_H;
                _glyphRects[ch] = new Rectangle(ox, oy, GLYPH_W, GLYPH_H);

                byte[] bits = GetGlyphBits((char)ch);
                for (int gy = 0; gy < GLYPH_H && gy < bits.Length; gy++)
                for (int gx = 0; gx < GLYPH_W; gx++)
                {
                    if ((bits[gy] & (1 << (GLYPH_W - 1 - gx))) != 0)
                        data[(oy + gy) * texW + (ox + gx)] = Color.White;
                }
            }

            Texture = new Texture2D(device, texW, texH);
            Texture.SetData(data);
        }

        /// <summary>Measure a string in pixels.</summary>
        public Vector2 MeasureString(string text)
        {
            if (string.IsNullOrEmpty(text)) return Vector2.Zero;
            return new Vector2(text.Length * GLYPH_W, GLYPH_H);
        }

        /// <summary>
        /// Draw text using the given SpriteBatch (caller manages Begin/End).
        /// </summary>
        public void DrawString(SpriteBatch sb, string text, Vector2 position, Color color)
        {
            if (string.IsNullOrEmpty(text)) return;
            float x = position.X;
            float y = position.Y;
            foreach (char ch in text)
            {
                if (ch >= 32 && ch < 127)
                {
                    var rect = _glyphRects[ch];
                    sb.Draw(Texture, new Vector2(x, y), rect, color,
                        0f, Vector2.Zero, 1f, SpriteEffects.None, 0f);
                }
                x += GLYPH_W;
            }
        }

        public void Dispose() => Texture?.Dispose();

